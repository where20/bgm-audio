def fix_lyrics():
    with open(MUSIC_JSON, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    for song in data['playlist']:
        meme = song.get('meme', '')
        
        if meme == '搭子文化':
            song['lyrics'] = DZWH_LYRICS
            print(f'✅ 修复歌词: {meme}')
        
        elif meme == '活人感':
            song['lyrics'] = HRG_LYRICS
            print(f'✅ 修复歌词: {meme}')
        
        elif meme == '班味':
            # 清理开头的 ``` 标记
            if song.get('lyrics', '').startswith('```'):
                song['lyrics'] = song['lyrics'].replace('```\n', '', 1).rstrip('`')
                print(f'✅ 清理格式: {meme}')
        
        elif meme == '酸黄瓜':
            song['lyrics'] = SHG_LYRICS
            print(f'✅ 修复歌词: {meme}')
        
        elif meme == '养龙虾':
            song['lyrics'] = YLCX_LYRICS
            print(f'✅ 修复歌词: {meme}')
        
        elif meme == '邪修外耗':
            song['lyrics'] = XXWH_LYRICS
            print(f'✅ 添加歌词: {meme}')
    
    with open(MUSIC_JSON, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print('\n✅ music.json 歌词全部修复完成！')

